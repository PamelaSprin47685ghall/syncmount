//! Import an existing POSIX directory tree into a client database.
//!
//! This is the offline half of the migration path: instead of mounting an
//! empty database and copying the tree through FUSE, `syncmount import` walks
//! a directory, chunks every regular file with BLAKE3 and writes
//! `objects`/`names`/`chunks`/`object_chunks` directly. The result behaves
//! exactly like a tree created through FUSE, so the normal seed path uploads
//! it on the first connection to an empty server.
//!
//! # Determinism
//!
//! `ino = BLAKE3("sm/v2/import\0" || path)[..16]`, so importing the same tree
//! on several machines yields the same inode ids. A hard-link group shares the
//! id of the first path in the deterministic depth-first order used here.
//! Re-running an import against the same database is a no-op: every row is
//! written with an upsert keyed by the same identity.
//!
//! # What is imported
//!
//! Directories, regular files and symbolic links. Hard links become several
//! `names` rows for one `objects` row. Names that belonged to the old POSIX
//! daemon (`.syncmount*`, `.audit.log`) are skipped. Symbolic links are never
//! followed; a link is stored as a link. Special files (FIFO, socket, device)
//! are refused rather than silently dropped.
//!
//! # Batching
//!
//! The tree is walked in sorted depth-first order so parents always precede
//! their children. Entries are committed in batches of 256 objects or 64 MiB
//! of file content; a single file larger than the byte budget is written in
//! its own sequence of transactions. An interrupted import leaves a partial
//! but consistent tree, and re-running it completes the work.

use std::collections::{HashMap, HashSet};
use std::ffi::OsStr;
use std::fs::{self, File, Metadata};
use std::io::Read;
use std::os::unix::ffi::OsStrExt;
use std::os::unix::fs::{FileTypeExt, MetadataExt};
use std::path::{Path, PathBuf};

use rusqlite::{OptionalExtension, params};

use super::db::{ClientDb, DbError, Ino};
use crate::store::sqlite::{
    CHUNK_BYTES, ChunkRef, DEFAULT_EPOCH, Object, ObjectKind, ROOT_INO, ROOT_MODE, ROOT_NLINK,
    WriteTx, chunk_hash, file_root, keys,
};

/// Objects or entries per commit.
const BATCH_ENTRIES: usize = 256;

/// File bytes per commit.
const BATCH_BYTES: u64 = 64 << 20;

/// Maximum directory nesting accepted.
const MAX_DEPTH: usize = 512;

/// Maximum `names.path` length in bytes (the schema check).
const MAX_PATH_BYTES: usize = 4096;

/// How one import should behave.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ImportOptions {
    /// Clear the existing tree, outbox and chunk table before importing.
    ///
    /// Without it an existing, already imported tree is updated in place and a
    /// conflicting entry is refused. With it the database becomes a fresh
    /// replica of the source tree, ready to seed.
    pub replace: bool,
    /// Generate the deterministic seed outbox events after the import.
    ///
    /// The client would generate the same events on its first connection to
    /// an empty server; doing it here makes the upload inspectable offline.
    pub seed: bool,
}

/// What one import did.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ImportReport {
    /// Unique inodes written, including the root.
    pub objects: u64,
    /// Directory entries written, including the root. Equals `objects` plus
    /// the extra names of hard links.
    pub entries: u64,
    pub dirs: u64,
    pub files: u64,
    pub symlinks: u64,
    /// Additional names of an inode that already had one (hard links).
    pub hardlinks: u64,
    /// Chunk references written (file content blocks, not distinct hashes).
    pub chunks: u64,
    /// Bytes of regular-file content read.
    pub bytes: u64,
    /// Reserved daemon names skipped.
    pub skipped: u64,
    /// Outbox events generated by [`ImportOptions::seed`].
    pub seed_events: u64,
}

/// Everything an import can refuse.
#[derive(Debug, thiserror::Error)]
pub enum ImportError {
    #[error("source {path}: {source}")]
    Io {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("database: {0}")]
    Db(#[from] DbError),
    #[error("sqlite: {0}")]
    Sqlite(#[from] rusqlite::Error),
    #[error("source {0} is not a directory (symlinks are not followed)")]
    SourceNotDirectory(PathBuf),
    #[error("unsupported file type at {path}: {kind}")]
    Unsupported { path: String, kind: &'static str },
    #[error("name at {path} is not valid UTF-8")]
    NonUtf8 { path: String },
    #[error("invalid name {name:?} at {path}: {reason}")]
    InvalidName {
        path: String,
        name: String,
        reason: &'static str,
    },
    #[error("path {0} is longer than 4096 bytes")]
    PathTooLong(String),
    #[error("directory tree is deeper than {MAX_DEPTH} levels at {0}")]
    TooDeep(String),
    #[error("conflict at {path}: {reason}; use --replace to rebuild the database tree")]
    Conflict { path: String, reason: String },
    #[error("database already contains applied server events (applied_seq={0}); use --replace")]
    AlreadySynced(i64),
    #[error("database has {0} unsent outbox operations; sync first or use --replace")]
    OutboxNotEmpty(u64),
    #[error("database has seen server epoch {0}; use --replace for a fresh import")]
    EpochNotFresh(i64),
    #[error("source changed while it was being imported: {0}")]
    SourceChanged(String),
    #[error("inode id collision at {0}")]
    InoCollision(String),
}

/// Import `source` into the client database at `db_path`.
///
/// `cluster` is the PSK-derived namespace guard the client will use to open
/// the database later; a mismatch makes the client refuse the file.
pub fn import_tree(
    source: impl AsRef<Path>,
    db_path: impl AsRef<Path>,
    cluster: [u8; 16],
    options: ImportOptions,
) -> Result<ImportReport, ImportError> {
    let db = ClientDb::open(db_path.as_ref(), cluster)?;
    import_into(&db, source.as_ref(), options)
}

/// Import `source` into an already open database.
pub fn import_into(
    db: &ClientDb,
    source: &Path,
    options: ImportOptions,
) -> Result<ImportReport, ImportError> {
    check_source(source)?;
    if options.replace {
        clear_tree(db)?;
    } else {
        let applied = db.applied_seq()?;
        if applied > 0 {
            return Err(ImportError::AlreadySynced(applied));
        }
        let pending = db.pending_outbox()?;
        if pending > 0 {
            return Err(ImportError::OutboxNotEmpty(pending));
        }
        let epoch = db.epoch()?;
        if epoch != DEFAULT_EPOCH {
            return Err(ImportError::EpochNotFresh(epoch));
        }
    }

    let mut importer = Importer::new(db);
    importer.walk_root(source)?;
    importer.finish()?;
    let mut report = importer.report;
    if options.seed {
        let epoch = db.epoch()?;
        let seed = db.seed(epoch)?;
        report.seed_events = seed.events;
    }
    Ok(report)
}

/// The deterministic inode id of one path inside the imported tree.
pub(crate) fn derive_ino(path: &str) -> Ino {
    let mut hasher = blake3::Hasher::new();
    hasher.update(b"sm/v2/import\0");
    hasher.update(path.as_bytes());
    let digest = hasher.finalize();
    let mut ino = [0u8; 16];
    ino.copy_from_slice(&digest.as_bytes()[..16]);
    if ino == ROOT_INO {
        ino[0] = 1;
    }
    ino
}

fn check_source(source: &Path) -> Result<(), ImportError> {
    let metadata = fs::symlink_metadata(source).map_err(|error| io_error(source, error))?;
    if !metadata.file_type().is_dir() {
        return Err(ImportError::SourceNotDirectory(source.to_path_buf()));
    }
    Ok(())
}

/// Reset the database to an empty client tree.
fn clear_tree(db: &ClientDb) -> Result<(), ImportError> {
    db.write(|tx| {
        tx.conn().execute("DELETE FROM outbox_chunks", [])?;
        tx.conn().execute("DELETE FROM outbox", [])?;
        tx.conn().execute("DELETE FROM object_chunks", [])?;
        tx.conn().execute("DELETE FROM names", [])?;
        tx.conn()
            .execute("DELETE FROM objects WHERE ino <> ?1", [ROOT_INO.as_slice()])?;
        tx.conn().execute("DELETE FROM chunks", [])?;
        tx.conn().execute(
            "DELETE FROM fuse_inos WHERE ino <> ?1",
            [ROOT_INO.as_slice()],
        )?;
        tx.conn().execute("DELETE FROM events", [])?;

        let root = Object {
            ino: ROOT_INO,
            kind: ObjectKind::Dir,
            mode: ROOT_MODE,
            uid: 0,
            gid: 0,
            mtime_ns: 0,
            size: 0,
            file_root: file_root(ObjectKind::Dir, None, &[]),
            block_count: 0,
            target: None,
            nlink: ROOT_NLINK,
            deleted: false,
            created_seq: 0,
            updated_seq: 0,
        };
        tx.put_object(&root)?;
        tx.set_meta_i64(keys::APPLIED_SEQ, 0)?;
        tx.set_meta_i64(keys::COVERED_SEQ, 0)?;
        tx.set_meta_i64(keys::EPOCH, DEFAULT_EPOCH)?;
        tx.set_meta_i64(keys::DIRTY, 0)?;
        tx.set_meta_i64(keys::FUSE_INO_NEXT, 2)?;
        tx.set_meta_i64("local_seq", 0)?;
        let state = tx.state_hash()?;
        tx.set_meta_blob(keys::STATE_HASH, &state)?;
        Ok(())
    })?;
    Ok(())
}

struct Entry {
    /// Absolute path inside the tree; the root is `/`.
    path: String,
    parent: Ino,
    /// `None` only for the root.
    name: Option<String>,
    ino: Ino,
    kind: ObjectKind,
    mode: u32,
    uid: u32,
    gid: u32,
    mtime_ns: i64,
    size: u64,
    target: Option<Vec<u8>>,
    source: PathBuf,
}

struct Importer<'a> {
    db: &'a ClientDb,
    report: ImportReport,
    pending: Vec<Entry>,
    pending_bytes: u64,
    hardlinks: HashMap<(u64, u64), Ino>,
    used_inos: HashMap<Ino, String>,
    seen: HashSet<Ino>,
}

impl<'a> Importer<'a> {
    fn new(db: &'a ClientDb) -> Self {
        Self {
            db,
            report: ImportReport::default(),
            pending: Vec::new(),
            pending_bytes: 0,
            hardlinks: HashMap::new(),
            used_inos: HashMap::new(),
            seen: HashSet::new(),
        }
    }

    fn walk_root(&mut self, source: &Path) -> Result<(), ImportError> {
        let metadata = fs::symlink_metadata(source).map_err(|error| io_error(source, error))?;
        if !metadata.file_type().is_dir() {
            return Err(ImportError::SourceNotDirectory(source.to_path_buf()));
        }
        let root = make_entry(
            "/".to_owned(),
            ROOT_INO,
            ROOT_INO,
            None,
            source.to_path_buf(),
            &metadata,
            ObjectKind::Dir,
            None,
        );
        self.push(root)?;
        self.walk_dir(source, "/", ROOT_INO, 1)
    }

    fn walk_dir(
        &mut self,
        dir: &Path,
        dir_path: &str,
        dir_ino: Ino,
        depth: usize,
    ) -> Result<(), ImportError> {
        if depth > MAX_DEPTH {
            return Err(ImportError::TooDeep(dir_path.to_owned()));
        }

        let mut children = Vec::new();
        for item in fs::read_dir(dir).map_err(|error| io_error(dir, error))? {
            let item = item.map_err(|error| io_error(dir, error))?;
            let name_os = item.file_name();
            if is_reserved(&name_os) {
                self.report.skipped += 1;
                continue;
            }
            let name = name_os
                .to_str()
                .ok_or_else(|| ImportError::NonUtf8 {
                    path: dir.join(&name_os).display().to_string(),
                })?
                .to_owned();
            validate_component(&name, dir_path)?;
            let full = item.path();
            let metadata = fs::symlink_metadata(&full).map_err(|error| io_error(&full, error))?;
            let path = join_path(dir_path, &name);
            if path.len() > MAX_PATH_BYTES {
                return Err(ImportError::PathTooLong(path));
            }
            children.push((name, full, metadata, path));
        }

        // `read_dir` order is not stable across filesystems or runs. Sorting
        // makes the first path of a hard-link group, and therefore its inode
        // id, deterministic.
        children.sort_by(|left, right| left.0.as_bytes().cmp(right.0.as_bytes()));

        for (name, full, metadata, path) in children {
            let file_type = metadata.file_type();
            if file_type.is_dir() {
                let ino = self.allocate_ino(&path)?;
                let entry = make_entry(
                    path.clone(),
                    dir_ino,
                    ino,
                    Some(name),
                    full.clone(),
                    &metadata,
                    ObjectKind::Dir,
                    None,
                );
                self.push(entry)?;
                self.walk_dir(&full, &path, ino, depth + 1)?;
            } else if file_type.is_file() {
                let ino = self.shared_ino(&path, &metadata)?;
                let entry = make_entry(
                    path,
                    dir_ino,
                    ino,
                    Some(name),
                    full,
                    &metadata,
                    ObjectKind::File,
                    None,
                );
                self.push(entry)?;
            } else if file_type.is_symlink() {
                let target = fs::read_link(&full).map_err(|error| io_error(&full, error))?;
                let bytes = target.as_os_str().as_bytes().to_vec();
                if bytes.is_empty() || bytes.len() > MAX_PATH_BYTES || bytes.contains(&0) {
                    return Err(ImportError::InvalidName {
                        path,
                        name,
                        reason: "symlink target is empty, contains NUL, or is longer than 4096 bytes",
                    });
                }
                let ino = self.shared_ino(&path, &metadata)?;
                let entry = make_entry(
                    path,
                    dir_ino,
                    ino,
                    Some(name),
                    full,
                    &metadata,
                    ObjectKind::Symlink,
                    Some(bytes),
                );
                self.push(entry)?;
            } else {
                return Err(ImportError::Unsupported {
                    path,
                    kind: special_kind(&file_type),
                });
            }
        }
        Ok(())
    }

    fn allocate_ino(&mut self, path: &str) -> Result<Ino, ImportError> {
        let ino = derive_ino(path);
        match self.used_inos.get(&ino) {
            Some(existing) if existing != path => Err(ImportError::InoCollision(path.to_owned())),
            Some(_) => Ok(ino),
            None => {
                self.used_inos.insert(ino, path.to_owned());
                Ok(ino)
            }
        }
    }

    /// The inode id for a non-directory. Hard links to the same `(device,
    /// inode)` reuse the id of the first path seen.
    fn shared_ino(&mut self, path: &str, metadata: &Metadata) -> Result<Ino, ImportError> {
        if metadata.nlink() > 1 {
            let key = (metadata.dev(), metadata.ino());
            if let Some(ino) = self.hardlinks.get(&key) {
                self.report.hardlinks += 1;
                return Ok(*ino);
            }
            let ino = self.allocate_ino(path)?;
            self.hardlinks.insert(key, ino);
            Ok(ino)
        } else {
            self.allocate_ino(path)
        }
    }

    fn push(&mut self, entry: Entry) -> Result<(), ImportError> {
        if entry.kind.is_file() && entry.size > BATCH_BYTES {
            self.flush()?;
            return self.import_large_file(&entry);
        }
        if entry.kind.is_file() {
            self.pending_bytes = self.pending_bytes.saturating_add(entry.size);
        }
        self.pending.push(entry);
        if self.pending.len() >= BATCH_ENTRIES || self.pending_bytes >= BATCH_BYTES {
            self.flush()?;
        }
        Ok(())
    }

    fn flush(&mut self) -> Result<(), ImportError> {
        if self.pending.is_empty() {
            return Ok(());
        }
        let batch = std::mem::take(&mut self.pending);
        self.pending_bytes = 0;
        self.check_batch(&batch)?;
        self.db.write(|tx| {
            for entry in &batch {
                write_entry(tx, entry)?;
            }
            Ok(())
        })?;
        for entry in &batch {
            self.count(entry);
        }
        Ok(())
    }

    /// Refuse a batch that would silently steal an existing name or path.
    ///
    /// The process holds the database's single-writer lock, so a read here
    /// cannot race another writer. `--replace` has already cleared the tree.
    fn check_batch(&self, batch: &[Entry]) -> Result<(), ImportError> {
        let snapshot = self.db.read()?;
        let mut by_name = snapshot
            .conn()
            .prepare("SELECT ino FROM names WHERE parent = ?1 AND name = ?2")?;
        let mut by_path = snapshot
            .conn()
            .prepare("SELECT ino, parent, name FROM names WHERE path = ?1")?;
        let mut by_ino = snapshot
            .conn()
            .prepare("SELECT kind FROM objects WHERE ino = ?1")?;

        for entry in batch {
            let existing_kind: Option<String> = by_ino
                .query_row([entry.ino.as_slice()], |row| row.get(0))
                .optional()?;
            if let Some(kind) = existing_kind {
                if kind != entry.kind.as_str() {
                    return Err(ImportError::Conflict {
                        path: entry.path.clone(),
                        reason: format!(
                            "the path is a {kind} in the database but a {} in the source",
                            entry.kind.as_str()
                        ),
                    });
                }
            }
            let Some(name) = &entry.name else {
                continue;
            };
            let existing: Option<Vec<u8>> = by_name
                .query_row(params![entry.parent.as_slice(), name], |row| row.get(0))
                .optional()?;
            if let Some(bytes) = existing {
                if bytes.as_slice() != entry.ino.as_slice() {
                    return Err(ImportError::Conflict {
                        path: entry.path.clone(),
                        reason: "the name already refers to another inode".to_owned(),
                    });
                }
            }

            let existing_path: Option<(Vec<u8>, Vec<u8>, String)> = by_path
                .query_row([entry.path.as_str()], |row| {
                    Ok((row.get(0)?, row.get(1)?, row.get(2)?))
                })
                .optional()?;
            if let Some((ino, parent, existing_name)) = existing_path {
                if ino.as_slice() != entry.ino.as_slice()
                    || parent.as_slice() != entry.parent.as_slice()
                    || existing_name != *name
                {
                    return Err(ImportError::Conflict {
                        path: entry.path.clone(),
                        reason: "the path already belongs to another entry".to_owned(),
                    });
                }
            }
        }
        Ok(())
    }

    /// A file larger than one batch: write its chunks in 64 MiB transactions,
    /// then publish the object and its chunk list in one final transaction.
    fn import_large_file(&mut self, entry: &Entry) -> Result<(), ImportError> {
        self.check_batch(std::slice::from_ref(entry))?;
        let mut file =
            open_regular(&entry.source).map_err(|error| io_error(&entry.source, error))?;
        let mut buffer = vec![0u8; CHUNK_BYTES as usize];
        let mut refs: Vec<ChunkRef> = Vec::new();
        let mut batch: Vec<([u8; 32], u32, Vec<u8>)> = Vec::new();
        let mut batch_bytes = 0u64;
        let mut chunk_no = 0u32;

        loop {
            let filled = read_chunk(&mut file, &mut buffer)
                .map_err(|error| io_error(&entry.source, error))?;
            if filled == 0 {
                break;
            }
            let data = &buffer[..filled];
            let hash = chunk_hash(data);
            let len = u32::try_from(filled)
                .map_err(|_| ImportError::SourceChanged(entry.path.clone()))?;
            refs.push(ChunkRef {
                chunk_no,
                hash,
                offset: u64::from(chunk_no) * u64::from(CHUNK_BYTES),
                len,
            });
            batch.push((hash, len, data.to_vec()));
            batch_bytes = batch_bytes.saturating_add(filled as u64);
            if batch_bytes >= BATCH_BYTES {
                self.write_chunk_batch(&batch)?;
                batch.clear();
                batch_bytes = 0;
            }
            chunk_no = chunk_no
                .checked_add(1)
                .ok_or_else(|| ImportError::SourceChanged(entry.path.clone()))?;
            if filled < buffer.len() {
                break;
            }
        }
        if !batch.is_empty() {
            self.write_chunk_batch(&batch)?;
        }

        let read_bytes: u64 = refs.iter().map(|chunk| u64::from(chunk.len)).sum();
        if read_bytes != entry.size {
            return Err(ImportError::SourceChanged(entry.path.clone()));
        }

        self.db.write(|tx| {
            let block_count =
                u32::try_from(refs.len()).map_err(|_| DbError::Corrupt("too many chunks"))?;
            let object = Object {
                ino: entry.ino,
                kind: entry.kind,
                mode: entry.mode,
                uid: entry.uid,
                gid: entry.gid,
                mtime_ns: entry.mtime_ns,
                size: entry.size,
                file_root: file_root(ObjectKind::File, None, &refs),
                block_count,
                target: None,
                nlink: 1,
                deleted: false,
                created_seq: 0,
                updated_seq: 0,
            };
            tx.put_object(&object)?;
            tx.set_object_chunks(entry.ino, &refs)?;
            if let Some(name) = &entry.name {
                insert_name(tx, entry, name)?;
            }
            ClientDb::next_fuse_ino(tx, entry.ino)?;
            Ok(())
        })?;
        self.count(entry);
        Ok(())
    }

    fn write_chunk_batch(&self, batch: &[([u8; 32], u32, Vec<u8>)]) -> Result<(), ImportError> {
        self.db.write(|tx| {
            for (hash, len, data) in batch {
                tx.put_chunk(*hash, *len, Some(data))?;
            }
            Ok(())
        })?;
        Ok(())
    }

    fn finish(&mut self) -> Result<(), ImportError> {
        self.flush()?;
        self.db.write(|tx| {
            tx.conn().execute(NLINK_SQL, [])?;
            tx.conn().execute(RECOUNT_SQL, [])?;
            let state = tx.state_hash()?;
            tx.set_meta_blob(keys::STATE_HASH, &state)?;
            Ok(())
        })?;
        Ok(())
    }

    fn count(&mut self, entry: &Entry) {
        self.report.entries += 1;
        if !self.seen.insert(entry.ino) {
            return;
        }
        self.report.objects += 1;
        match entry.kind {
            ObjectKind::Dir => self.report.dirs += 1,
            ObjectKind::File => {
                self.report.files += 1;
                self.report.bytes = self.report.bytes.saturating_add(entry.size);
                self.report.chunks = self
                    .report
                    .chunks
                    .saturating_add(entry.size.div_ceil(u64::from(CHUNK_BYTES)));
            }
            ObjectKind::Symlink => self.report.symlinks += 1,
            _ => {}
        }
    }
}

#[allow(clippy::too_many_arguments)]
fn make_entry(
    path: String,
    parent: Ino,
    ino: Ino,
    name: Option<String>,
    source: PathBuf,
    metadata: &Metadata,
    kind: ObjectKind,
    target: Option<Vec<u8>>,
) -> Entry {
    let size = match kind {
        ObjectKind::File => metadata.len(),
        ObjectKind::Symlink => target.as_ref().map_or(0, |value| value.len() as u64),
        _ => 0,
    };
    Entry {
        path,
        parent,
        name,
        ino,
        kind,
        mode: metadata.mode() & 0o7777,
        uid: metadata.uid(),
        gid: metadata.gid(),
        mtime_ns: metadata_mtime_ns(metadata),
        size,
        target,
        source,
    }
}

fn write_entry(tx: &WriteTx<'_>, entry: &Entry) -> Result<(), DbError> {
    let chunks = if entry.kind.is_file() {
        Some(write_file_chunks(tx, entry)?)
    } else {
        None
    };
    let (root, block_count) = match entry.kind {
        ObjectKind::File => {
            let refs = chunks.as_deref().unwrap_or(&[]);
            (
                file_root(ObjectKind::File, None, refs),
                u32::try_from(refs.len()).map_err(|_| DbError::Corrupt("too many chunks"))?,
            )
        }
        ObjectKind::Dir => (file_root(ObjectKind::Dir, None, &[]), 0),
        ObjectKind::Symlink => (
            file_root(ObjectKind::Symlink, entry.target.as_deref(), &[]),
            0,
        ),
        _ => return Err(DbError::Corrupt("imported an unsupported object kind")),
    };

    let object = Object {
        ino: entry.ino,
        kind: entry.kind,
        mode: entry.mode,
        uid: entry.uid,
        gid: entry.gid,
        mtime_ns: entry.mtime_ns,
        size: entry.size,
        file_root: root,
        block_count,
        target: entry.target.clone(),
        nlink: 1,
        deleted: false,
        created_seq: 0,
        updated_seq: 0,
    };
    tx.put_object(&object)?;
    match &chunks {
        Some(refs) => tx.set_object_chunks(entry.ino, refs)?,
        None => tx.set_object_chunks(entry.ino, &[])?,
    }
    if let Some(name) = &entry.name {
        insert_name(tx, entry, name)?;
    }
    ClientDb::next_fuse_ino(tx, entry.ino)?;
    Ok(())
}

fn insert_name(tx: &WriteTx<'_>, entry: &Entry, name: &str) -> Result<(), DbError> {
    tx.conn().execute(
        "INSERT INTO names (parent, name, ino, path) VALUES (?1, ?2, ?3, ?4)
         ON CONFLICT(parent, name) DO UPDATE SET ino = excluded.ino, path = excluded.path",
        params![
            entry.parent.as_slice(),
            name,
            entry.ino.as_slice(),
            entry.path
        ],
    )?;
    Ok(())
}

fn write_file_chunks(tx: &WriteTx<'_>, entry: &Entry) -> Result<Vec<ChunkRef>, DbError> {
    let mut file = open_regular(&entry.source).map_err(|error| io_db(&entry.source, error))?;
    let mut buffer = vec![0u8; CHUNK_BYTES as usize];
    let mut refs = Vec::new();
    let mut chunk_no = 0u32;
    loop {
        let filled =
            read_chunk(&mut file, &mut buffer).map_err(|error| io_db(&entry.source, error))?;
        if filled == 0 {
            break;
        }
        let data = &buffer[..filled];
        let hash = chunk_hash(data);
        let len = u32::try_from(filled).map_err(|_| DbError::Corrupt("chunk is too large"))?;
        tx.put_chunk(hash, len, Some(data))?;
        refs.push(ChunkRef {
            chunk_no,
            hash,
            offset: u64::from(chunk_no) * u64::from(CHUNK_BYTES),
            len,
        });
        chunk_no = chunk_no
            .checked_add(1)
            .ok_or(DbError::Corrupt("too many chunks"))?;
        if filled < buffer.len() {
            break;
        }
    }
    let read_bytes: u64 = refs.iter().map(|chunk| u64::from(chunk.len)).sum();
    if read_bytes != entry.size {
        return Err(io_db(
            &entry.source,
            std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                "size changed while it was being imported",
            ),
        ));
    }
    Ok(refs)
}

/// Open a regular file without following a symbolic link.
///
/// The walk already classified the entry with `symlink_metadata`; `O_NOFOLLOW`
/// closes the window in which the name could be replaced by a link before the
/// content is read.
fn open_regular(path: &Path) -> std::io::Result<File> {
    let flags =
        rustix::fs::OFlags::RDONLY | rustix::fs::OFlags::CLOEXEC | rustix::fs::OFlags::NOFOLLOW;
    let fd =
        rustix::fs::open(path, flags, rustix::fs::Mode::empty()).map_err(std::io::Error::from)?;
    Ok(File::from(fd))
}

/// Fill `buffer` as far as the file allows and return the byte count.
fn read_chunk(file: &mut File, buffer: &mut [u8]) -> std::io::Result<usize> {
    let mut filled = 0usize;
    while filled < buffer.len() {
        match file.read(&mut buffer[filled..]) {
            Ok(0) => break,
            Ok(count) => filled += count,
            Err(error) if error.kind() == std::io::ErrorKind::Interrupted => continue,
            Err(error) => return Err(error),
        }
    }
    Ok(filled)
}

fn metadata_mtime_ns(metadata: &Metadata) -> i64 {
    let seconds = metadata.mtime();
    if seconds < 0 {
        return 0;
    }
    seconds
        .saturating_mul(1_000_000_000)
        .saturating_add(metadata.mtime_nsec())
}

fn is_reserved(name: &OsStr) -> bool {
    crate::store::is_reserved_name(name) || name.as_bytes().starts_with(b".syncmount-")
}

fn validate_component(name: &str, parent: &str) -> Result<(), ImportError> {
    if name.is_empty() || name == "." || name == ".." || name.contains('/') || name.contains('\0') {
        return Err(ImportError::InvalidName {
            path: parent.to_owned(),
            name: name.to_owned(),
            reason: "not a single path component",
        });
    }
    if name.chars().count() > 255 {
        return Err(ImportError::InvalidName {
            path: parent.to_owned(),
            name: name.to_owned(),
            reason: "longer than 255 characters",
        });
    }
    Ok(())
}

fn special_kind(file_type: &fs::FileType) -> &'static str {
    if file_type.is_fifo() {
        "fifo"
    } else if file_type.is_socket() {
        "socket"
    } else if file_type.is_char_device() {
        "character device"
    } else if file_type.is_block_device() {
        "block device"
    } else {
        "unknown"
    }
}

fn join_path(parent: &str, name: &str) -> String {
    if parent == "/" {
        format!("/{name}")
    } else {
        format!("{parent}/{name}")
    }
}

fn io_error(path: &Path, source: std::io::Error) -> ImportError {
    ImportError::Io {
        path: path.to_path_buf(),
        source,
    }
}

fn io_db(path: &Path, error: std::io::Error) -> DbError {
    DbError::Io(std::io::Error::new(
        error.kind(),
        format!("{}: {error}", path.display()),
    ))
}

/// Recompute every live object's link count from the `names` table.
///
/// A directory counts its implicit `.` and the `..` held by each child
/// directory (`2 + child directories`); any other object counts its names.
/// Running this once after the import makes a repeated import idempotent even
/// though rows are written in batches.
const NLINK_SQL: &str = r#"
UPDATE objects SET nlink = CASE
    WHEN kind = 'dir' THEN 2 + (
        SELECT COUNT(*) FROM names n
        JOIN objects c ON c.ino = n.ino
        WHERE n.parent = objects.ino AND c.kind = 'dir' AND c.deleted = 0
    )
    ELSE (
        SELECT COUNT(*) FROM names n WHERE n.ino = objects.ino
    )
END
WHERE deleted = 0
"#;

/// The client refcount formula: object references plus outbox references.
const RECOUNT_SQL: &str = r#"
UPDATE chunks SET refcount =
      (SELECT COUNT(*) FROM object_chunks oc WHERE oc.chunk_hash = chunks.hash)
    + (SELECT COUNT(*) FROM outbox_chunks x WHERE x.chunk_hash = chunks.hash)
"#;

